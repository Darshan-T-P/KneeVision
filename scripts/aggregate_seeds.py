"""Aggregate per-seed validation/test metrics into reports/SEED_ROBUSTNESS.md.

Reads only existing JSON artifacts (models/*.json, test-eval JSONs); computes mean and
sample SD (ddof=1). Nothing is hard-coded.
"""
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M, T = ROOT / "models", ROOT / "reports" / "test_evals"
CORAL = "best_densenet121_ordinal_ordinal_soft_mixup_a04"
GROUPS = {
    "Soft CORAL + MixUp 0.4": [
        (M / f"{CORAL}.json", M / "final_ordinal_soft_mixup_a04_test.json"),
        (M / f"{CORAL}_seed7.json", T / f"{CORAL}_seed7.test.json"),
        (M / f"{CORAL}_seed123.json", T / f"{CORAL}_seed123.test.json"),
        (M / f"{CORAL}_seed2024.json", T / f"{CORAL}_seed2024.test.json"),
    ],
    "Multitask (OARSI aux heads) + soft CORAL + MixUp 0.4": [
        (M / "best_densenet121_multitask_ordinal_soft_mixup_a04.json", T / "best_densenet121_multitask_ordinal_soft_mixup_a04.test.json"),
        (M / "best_densenet121_multitask_ordinal_soft_mixup_a04_seed7.json", T / "best_densenet121_multitask_ordinal_soft_mixup_a04_seed7.test.json"),
        (M / "best_densenet121_multitask_ordinal_soft_mixup_a04_seed2024.json", T / "best_densenet121_multitask_ordinal_soft_mixup_a04_seed2024.test.json"),
    ],
    "Focal, no MixUp": [
        (M / "best_densenet121_focal_nomixup.json", T / "best_densenet121_focal_nomixup.test.json"),
        (M / "best_densenet121_focal_nomixup_seed123.json", T / "best_densenet121_focal_nomixup_seed123.test.json"),
        (M / "best_densenet121_focal_nomixup_seed7.json", T / "best_densenet121_focal_nomixup_seed7.test.json"),
    ],
}


def ms(v):
    return f"{st.mean(v):.4f} ± {st.stdev(v):.4f}" if len(v) > 1 else f"{v[0]:.4f}"


lines = ["# Seed robustness (generated by scripts/aggregate_seeds.py)", "",
         "Mean ± sample SD (ddof=1) over seeds. Validation = checkpoint-selection split; test = frozen held-out split, evaluated once per checkpoint.", ""]
for name, runs in GROUPS.items():
    rows, val, tq, tm, tw = [], [], [], [], []
    for vj, tj in runs:
        if not (vj.exists() and tj.exists()):
            print(f"missing: {vj.name} or {tj.name}", file=sys.stderr)
            continue
        v, t = json.loads(vj.read_text()), json.loads(tj.read_text())
        val.append(v["best_validation_qwk"]); tq.append(t["qwk"]); tm.append(t["mae"]); tw.append(t["within_1"])
        rows.append(f"| {v['seed']} | {v['epoch']} | {v['best_validation_qwk']:.4f} | {t['qwk']:.4f} | {t['mae']:.4f} | {t['within_1']*100:.2f}% | {t['accuracy']*100:.2f}% |")
    lines += [f"## {name} (n={len(rows)})", "", "| Seed | Best epoch | Val QWK | Test QWK | Test MAE | Test Within-1 | Test Acc |", "|---|---|---|---|---|---|---|", *rows]
    if rows:
        lines += [f"| **mean ± SD** | | {ms(val)} | {ms(tq)} | {ms(tm)} | {ms([x*100 for x in tw])}% | |"]
    lines += [""]
(ROOT / "reports" / "SEED_ROBUSTNESS.md").write_text("\n".join(lines))
print("\n".join(lines))
