"""Measure model complexity: parameters, checkpoint size, FLOPs, and inference latency.

FLOPs are counted with torch.utils.flop_counter (counts 2 x multiply-accumulates) for one 224x224 image through the
main KL head only (auxiliary heads are not used at inference). Latency: median per-batch time on this machine's GPU
(fp32 and fp16 autocast, batch 1 and 32; 10 warm-up, 50 timed iterations, CUDA-synchronised). Latency is
hardware-specific and must not be compared with numbers from other hardware.

Usage: uv run python scripts/measure_complexity.py
"""
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import torch
from torch.utils.flop_counter import FlopCounterMode

from kneevision.config.settings import PROJECT_ROOT
from kneevision.models.image_model import load_trained_model
from kneevision.utils.helpers import get_device

M = PROJECT_ROOT / "models"
MODELS = {
    "DenseNet121 (plain CORAL)": "best_densenet121_ordinal_ordinal_soft_mixup_a04",
    "DenseNet121 + OARSI aux heads": "best_densenet121_multitask_ordinal_soft_mixup_a04",
    "ConvNeXt-Tiny": "best_convnext_tiny_ordinal_ordinal_soft_mixup_a04",
    "EfficientNet-B4": "best_efficientnet-b4_ordinal_ordinal_soft_mixup_a04",
    "Swin-T": "best_swin_t_ordinal_ordinal_soft_mixup_a04",
}


@torch.inference_mode()
def latency_ms(model, device, batch, amp, iters=50, warm=10):
    x = torch.randn(batch, 3, 224, 224, device=device)
    times = []
    for i in range(warm + iters):
        torch.cuda.synchronize()
        t = time.perf_counter()
        with torch.autocast("cuda", dtype=torch.float16, enabled=amp):
            model(x)
        torch.cuda.synchronize()
        if i >= warm:
            times.append((time.perf_counter() - t) * 1000)
    return statistics.median(times)


def main():
    device = get_device()
    assert device.type == "cuda", "latency measurement needs the GPU"
    rows = []
    for name, stem in MODELS.items():
        pt = M / f"{stem}.pt"
        model = load_trained_model(pt, device, num_classes=5).to(device).eval()
        params = sum(p.numel() for p in model.parameters())
        main_params = sum(p.numel() for n, p in model.named_parameters() if not n.startswith("aux_heads"))
        x = torch.randn(1, 3, 224, 224, device=device)
        with torch.inference_mode(), FlopCounterMode(display=False) as fc:
            model(x)
        r = {"model": name, "checkpoint": stem, "params_m_total": params / 1e6, "params_m_inference": main_params / 1e6,
             "ckpt_mb": pt.stat().st_size / 1e6, "gflops": fc.get_total_flops() / 1e9}
        for batch in (1, 32):
            for amp in (False, True):
                ms = latency_ms(model, device, batch, amp)
                r[f"ms_per_image_b{batch}_{'fp16' if amp else 'fp32'}"] = ms / batch
        rows.append(r)
        print(name, {k: round(v, 3) for k, v in r.items() if isinstance(v, float)}, flush=True)
        del model
        torch.cuda.empty_cache()

    L = ["# Model complexity (generated by scripts/measure_complexity.py)", "",
         f"GPU: {torch.cuda.get_device_name(0)}; torch {torch.__version__}. FLOPs = 2 x MACs for one 224x224 image, main KL head only. "
         "Latency = median ms per image (batch time / batch size). Latency is specific to this hardware.", "",
         "| Model | Params, inference (M) | Checkpoint (MB) | GFLOPs | ms/img b=1 fp32 | ms/img b=1 fp16 | ms/img b=32 fp32 | ms/img b=32 fp16 |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['model']} | {r['params_m_inference']:.1f} | {r['ckpt_mb']:.0f} | {r['gflops']:.2f} | "
                 f"{r['ms_per_image_b1_fp32']:.1f} | {r['ms_per_image_b1_fp16']:.1f} | {r['ms_per_image_b32_fp32']:.2f} | {r['ms_per_image_b32_fp16']:.2f} |")
    L += ["", "Reference (reported by Azad & Anik, IEEE Access 2025, their own hardware, not re-measured here): stacked ensemble "
          "77.3 M parameters, 335 MB, 13.14 GFLOPs (their FLOP definition not stated)."]
    (PROJECT_ROOT / "reports" / "COMPLEXITY.md").write_text("\n".join(L) + "\n")
    (PROJECT_ROOT / "reports" / "complexity.json").write_text(json.dumps(rows, indent=2))
    print("wrote reports/COMPLEXITY.md")


if __name__ == "__main__":
    main()
