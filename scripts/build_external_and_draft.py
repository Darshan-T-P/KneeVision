"""Build reports/PAPER_TABLES_EXTERNAL.md and reports/PAPER_DRAFT_SECTIONS.md from saved result files.

Every number is read from: reports/external_adapt/results.json (Tier A), reports/external_adapt_tierb/results.json
(Tier B), reports/SEED_ROBUSTNESS inputs (models/*.json, reports/test_evals/*.test.json), reports/complexity.json,
reports/xai_faithfulness.json. Nothing is typed by hand.
"""
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RP = ROOT / "reports"
A = json.loads((RP / "external_adapt" / "results.json").read_text())
B = json.loads((RP / "external_adapt_tierb" / "results.json").read_text())
CX = {r["model"]: r for r in json.loads((RP / "complexity.json").read_text())}
XAI = json.loads((RP / "xai_faithfulness.json").read_text())["methods"]


def ms(v, d=3, pct=False):
    v = [x * 100 for x in v] if pct else v
    f = f"{{:.{1 if pct else d}f}}"
    return f.format(v[0]) if len(v) == 1 else f"{f.format(st.mean(v))} ± {f.format(st.stdev(v))}"


def collect(results, group, key, method):
    return [r[method][key] for r in results.values() if r["group"] == group and method in r]


def test_json(stem):
    return json.loads((RP / "test_evals" / f"{stem}.test.json").read_text())


def seeds_stats(stems, key):
    vals = []
    for s in stems:
        p = RP / "test_evals" / f"{s}.test.json"
        vals.append(json.loads(p.read_text())[key] if p.exists() else json.loads((ROOT / "models/final_ordinal_soft_mixup_a04_test.json").read_text())[key])
    return vals


A_ = "best_densenet121_ordinal_ordinal_soft_mixup_a04"
MT_ = "best_densenet121_multitask_ordinal_soft_mixup_a04"
plain = [A_, A_ + "_seed7", A_ + "_seed123", A_ + "_seed2024"]
multi = [MT_, MT_ + "_seed7", MT_ + "_seed2024"]
plain_t = [f"{x}" if x != A_ else "final_ordinal_soft_mixup_a04" for x in plain]

# ---------------- external tables ----------------
ALL = {**A, **B}
GROUPS = ["plain CORAL (DenseNet121)", "multitask CORAL (DenseNet121)", "Focal baseline (DenseNet121)", "ConvNeXt-Tiny CORAL",
          "EfficientNet-B4 CORAL", "Swin-T CORAL", "short-schedule baseline (DenseNet121)", "domain-robust training (DenseNet121)"]
METHODS = [("zero_shot", "Zero-shot"), ("adabn", "AdaBN (unlabelled)"), ("recal_n50", "Recal. 50 labels"), ("recal_nall", "Recal. all 495 labels")]
L = ["# External validation tables (generated by scripts/build_external_and_draft.py)", "",
     "Independent cohort: Gornale & Patravali, Digital Knee X-ray Images (Mendeley Data, CC BY 4.0), Expert-I labels, 1,650 images. "
     "Fixed split: 30% development (n=495, used for any adaptation) / 70% held-out test (n=1,155, all values below). "
     "Mean ± sample SD over seeds (n shown). Only the Zero-shot row is clean generalization; the other rows adapt to the target site. "
     "Short-schedule rows use a 40-epoch schedule and must only be compared with each other. No patient IDs exist in this cohort, so "
     "images of one patient may fall on both sides of the split.", ""]
for key, title, pct in (("qwk", "Quadratic weighted kappa", False), ("mae", "MAE", False), ("within1", "Within-1 accuracy (%)", True),
                        ("acc", "Exact accuracy (%)", True), ("bin_acc", "Binary accuracy, KL0-1 vs KL2-4 (%)", True),
                        ("sens", "Binary sensitivity (%)", True), ("spec", "Binary specificity (%)", True), ("macro_f1", "Macro-F1", False)):
    L += [f"## {title}", "", "| Model | n | " + " | ".join(m[1] for m in METHODS) + " |", "|---|---|" + "---|" * len(METHODS)]
    for g in GROUPS:
        n = sum(1 for r in ALL.values() if r["group"] == g)
        if n:
            L.append(f"| {g} | {n} | " + " | ".join(("n/a" if not collect(ALL, g, key, m) else ms(collect(ALL, g, key, m), pct=pct)) for m, _ in METHODS) + " |")
    L.append("")
(RP / "PAPER_TABLES_EXTERNAL.md").write_text("\n".join(L) + "\n")

# ---------------- draft sections ----------------
def g(group, key, method="zero_shot", pct=False):
    return ms(collect(ALL, group, key, method), pct=pct)


pq, mq = seeds_stats(plain_t, "qwk"), seeds_stats(multi, "qwk")
pw, mw = seeds_stats(plain_t, "within_1"), seeds_stats(multi, "within_1")
pm, mm = seeds_stats(plain_t, "mae"), seeds_stats(multi, "mae")
D = CX["DenseNet121 (plain CORAL)"]
rb, bs = "domain-robust training (DenseNet121)", "short-schedule baseline (DenseNet121)"
T = f"""# Draft paper sections (generated by scripts/build_external_and_draft.py)

All numbers below are read from result files in this repository. This is a DRAFT for the author to edit: check every
claim against `reports/PAPER_TABLES.md`, `reports/PAPER_TABLES_EXTERNAL.md`, `reports/SEED_ROBUSTNESS.md` and
`reports/COMPLEXITY.md`, and add references.

## Results (internal, OAI-derived Kaggle split; frozen test set, N = 1,656, 828 patients)

On the five-grade Kellgren-Lawrence task a DenseNet121 trained with CORAL ordinal heads and soft cumulative targets under
MixUp (alpha = 0.4) reached a quadratic weighted kappa (QWK) of {ms(pq)} over {len(pq)} seeds (MAE {ms(pm)}; Within-1 accuracy
{ms(pw, pct=True)}%). Adding auxiliary heads supervised with the OAI per-compartment OARSI grades (JSN, osteophytes,
sclerosis, attrition) raised QWK to {ms(mq)} over {len(mq)} seeds (MAE {ms(mm)}; Within-1 {ms(mw, pct=True)}%) and reduced the
between-seed variability. Because the OARSI components are the radiographic criteria that define the KL grade, this is
additional supervision on the same images, not independent information. Confidence intervals for individual models
(patient-level cluster bootstrap, B = 1000) are in `PAPER_TABLES.md`. Exact five-class accuracy stayed around 63-66%;
most errors are between adjacent grades, and KL1 and KL3 remain the hardest grades.

## Efficiency

The inference model has {D['params_m_inference']:.1f} M parameters ({D['ckpt_mb']:.0f} MB, {D['gflops']:.2f} GFLOPs per 224x224
image; FLOPs counted as 2 x multiply-accumulates). Batch-32 latency on the authors' laptop GPU was
{D['ms_per_image_b32_fp32']:.1f} ms/image (fp32). Latency is hardware specific.

## External validation (independent hospital cohort, not seen in training)

Evaluated without retraining on 1,650 radiographs from a different source (held-out 70% = 1,155 images), the plain
CORAL DenseNet121 reached a zero-shot QWK of {g('plain CORAL (DenseNet121)', 'qwk')} and a binary (KL0-1 vs KL2-4) accuracy of
{g('plain CORAL (DenseNet121)', 'bin_acc', pct=True)}% (sensitivity {g('plain CORAL (DenseNet121)', 'sens', pct=True)}%, specificity
{g('plain CORAL (DenseNet121)', 'spec', pct=True)}%), against an internal QWK above 0.8: performance falls markedly under
site shift, with the model over-calling disease (high sensitivity, low specificity). Re-estimating batch-normalization
statistics on unlabelled target images raised QWK to {g('plain CORAL (DenseNet121)', 'qwk', 'adabn')}, and re-fitting the four
CORAL thresholds on 50 labelled target images raised it to {g('plain CORAL (DenseNet121)', 'qwk', 'recal_n50')}
(binary accuracy {g('plain CORAL (DenseNet121)', 'bin_acc', 'recal_n50', pct=True)}%). Global histogram equalization of the inputs,
applied at training and test time, reduced external performance (QWK 0.35 for seed 42 vs 0.56 without it; this single-seed comparison was run on all 1,650 images, before the development/test split was introduced).

Training with domain-robust augmentation (random aspect ratio, resolution degradation, gamma, contrast, noise) and
per-image intensity standardization improved external zero-shot QWK from {g(bs, 'qwk')} to {g(rb, 'qwk')} and binary accuracy from
{g(bs, 'bin_acc', pct=True)}% to {g(rb, 'bin_acc', pct=True)}% (matched 40-epoch schedules, {len(collect(ALL, rb, 'qwk', 'zero_shot'))} seeds); after
recalibration with 50 labelled images the external QWK was {g(rb, 'qwk', 'recal_n50')} (binary accuracy
{g(rb, 'bin_acc', 'recal_n50', pct=True)}%).

## Explainability

Insertion/deletion faithfulness (validation images; predicted-grade probability while 16x16 patches are revealed or removed
in saliency order): insertion AUC {XAI['gradcam']['insertion_auc_mean']:.3f} (Grad-CAM, n={XAI['gradcam']['n']}),
{XAI['scorecam']['insertion_auc_mean']:.3f} (Score-CAM, n={XAI['scorecam']['n']}), {XAI['lime']['insertion_auc_mean']:.3f} (LIME, n={XAI['lime']['n']}) versus
{XAI['random']['insertion_auc_mean']:.3f} for random saliency. Deletion AUC was {XAI['gradcam']['deletion_auc_mean']:.3f} / {XAI['scorecam']['deletion_auc_mean']:.3f} /
{XAI['lime']['deletion_auc_mean']:.3f} versus {XAI['random']['deletion_auc_mean']:.3f} (random), i.e. only marginally better than chance for
Grad-CAM and not better for Score-CAM or LIME. Per-image variability is large.

## Limitations (suggested text)

1. All training and internal evaluation use a single cohort (OAI-derived). On an independent hospital cohort, zero-shot
   performance dropped substantially; adaptation and robust training reduced but did not remove the gap.
2. External adaptation results use target-site data (unlabelled images or a few labelled images) and are not zero-shot
   generalization. The external cohort has no patient identifiers, so its development/test split may share patients.
3. External-cohort labels come from different annotators; KL1 in particular is inconsistently labelled between sources.
4. KL1 and KL3 recall remain low; five-class exact accuracy is about 63-66%.
5. The OARSI auxiliary labels and the clinical-text/fusion branch encode the components that define the KL grade;
   reported fusion performance reflects this definitional overlap, not independent clinical information.
6. Seed counts are small (2-4); differences below the seed-to-seed spread (about 0.01-0.03 QWK) should not be read as
   significant. Backbone comparisons were single-seed and used a recipe tuned on DenseNet121.
7. Explanation maps were evaluated quantitatively on a small subset; deletion faithfulness is close to chance.
8. The system is a research prototype evaluated retrospectively; it is not a validated diagnostic device.

## Claims to avoid

- Do not claim state-of-the-art, clinical readiness, or generalization to unseen sites without qualification.
- Do not claim CORAL outperforms Focal; the evidence is consistent but small-sample (Focal, no MixUp: 3 seeds).
- Do not present adapted external numbers as zero-shot.
- Do not compare short-schedule (40-epoch) results with the 100-epoch results.
"""
(RP / "PAPER_DRAFT_SECTIONS.md").write_text(T)
print("wrote reports/PAPER_TABLES_EXTERNAL.md and reports/PAPER_DRAFT_SECTIONS.md")
