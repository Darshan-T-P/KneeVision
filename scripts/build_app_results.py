"""Build docs/app_results.json: the verified numbers the Streamlit app displays (tracked in git, so cloud deploys have it).

Reads: reports/paper_metrics.json, reports/branches_tasks/branch_task_results.json, reports/external_adapt*/results.json,
reports/xai_faithfulness.json, reports/complexity.json, reports/test_evals/*.test.json.
Usage: uv run python scripts/build_app_results.py
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "reports"
rows = json.loads((R / "paper_metrics.json").read_text())
BR = json.loads((R / "branches_tasks/branch_task_results.json").read_text())
EA = json.loads((R / "external_adapt/results.json").read_text())
EB = json.loads((R / "external_adapt_tierb/results.json").read_text())
XAI = json.loads((R / "xai_faithfulness.json").read_text())["methods"]
CX = {r["model"]: r for r in json.loads((R / "complexity.json").read_text())}["DenseNet121 (plain CORAL)"]


def ms(v):
    return [float(np.mean(v)), float(np.std(v, ddof=1)) if len(v) > 1 else 0.0]


def grp(f):
    return [r for r in rows if f(r["model"])]


FINAL = lambda m: "aux heads" in m and "40-epoch" not in m  # noqa: E731
final = grp(FINAL)
out = {
    "note": "Generated by scripts/build_app_results.py from files in reports/. Test set: 1,656 radiographs (828 patients).",
    "branch_tasks": {
        "xray_final": {"label": "X-ray only (final model: CORAL + OARSI aux heads, 3-seed mean)",
                       "binary": ms([r["bin_acc"] * 100 for r in final]), "three_class": ms([r["tri_acc"] * 100 for r in final]),
                       "five_class": ms([r["acc"] * 100 for r in final]), "qwk": ms([r["qwk"] for r in final]),
                       "binary_auc": ms([r["bin_auc"] for r in final])},
        "clinical": {"label": "Clinical text (BioClinicalBERT)", "binary": BR["clinical"]["acc_binary"] * 100,
                     "three_class": BR["clinical"]["acc_3class_01_2_34"] * 100, "five_class": BR["clinical"]["acc5"] * 100, "qwk": BR["clinical"]["qwk"]},
        "fusion": {"label": "Fusion (X-ray + clinical)", "binary": BR["fusion"]["acc_binary"] * 100,
                   "three_class": BR["fusion"]["acc_3class_01_2_34"] * 100, "five_class": BR["fusion"]["acc5"] * 100, "qwk": BR["fusion"]["qwk"],
                   "binary_sensitivity": BR["fusion"]["sens_binary"] * 100, "binary_specificity": BR["fusion"]["spec_binary"] * 100},
    },
    "models": [],
    "per_class_recall_final": None,
    "xai": {k: {"n": v["n"], "insertion_auc": v["insertion_auc_mean"], "deletion_auc": v["deletion_auc_mean"]} for k, v in XAI.items()},
    "complexity": {"params_m": CX["params_m_inference"], "ckpt_mb": CX["ckpt_mb"], "gflops": CX["gflops"], "ms_per_image_b32_fp32": CX["ms_per_image_b32_fp32"]},
}
G = [("DenseNet121 · CORAL + OARSI aux heads (best)", FINAL),
     ("DenseNet121 · CORAL ordinal", lambda m: m.startswith("DenseNet121 · soft CORAL + MixUp 0.4 · seed")),
     ("Swin-T · CORAL ordinal", lambda m: m.startswith("Swin")), ("ConvNeXt-Tiny · CORAL ordinal", lambda m: m.startswith("ConvNeXt")),
     ("DenseNet121 · Focal loss", lambda m: "Focal, no MixUp" in m), ("EfficientNet-B4 · CORAL ordinal", lambda m: m.startswith("EfficientNet"))]
for name, f in G:
    rs = grp(f)
    out["models"].append({"model": name, "seeds": len(rs), "accuracy": ms([r["acc"] * 100 for r in rs]), "macro_f1": ms([r["macro_f1"] for r in rs]),
                          "auc": ms([r["macro_auc"] for r in rs]), "qwk": ms([r["qwk"] for r in rs]), "mae": ms([r["mae"] for r in rs]),
                          "within1": ms([r["within1"] * 100 for r in rs]), "params_m": ms([r["params_m"] for r in rs])[0]})
rec = []
for r in final:
    rec.append([r[f"KL{k}_recall"] * 100 for k in range(5)])
out["per_class_recall_final"] = np.mean(rec, 0).tolist()

ALL = {**EA, **EB}


def ext(group, m):
    rs = [r for r in ALL.values() if r["group"] == group and m in r]
    return {k: ms([r[m][k] for r in rs]) for k in ("qwk", "bin_acc", "sens", "spec")} | {"n_seeds": len(rs)}


out["external_shift"] = {
    "cohort": "Gornale & Patravali, Digital Knee X-ray Images (1,650 hospital radiographs, different source); held-out 70% (n=1,155)",
    "plain_zero_shot": ext("plain CORAL (DenseNet121)", "zero_shot"), "plain_adabn": ext("plain CORAL (DenseNet121)", "adabn"),
    "plain_recal50": ext("plain CORAL (DenseNet121)", "recal_n50"),
    "baseline40_zero_shot": ext("short-schedule baseline (DenseNet121)", "zero_shot"), "robust40_zero_shot": ext("domain-robust training (DenseNet121)", "zero_shot"),
    "robust40_recal50": ext("domain-robust training (DenseNet121)", "recal_n50"),
}
(ROOT / "docs" / "app_results.json").write_text(json.dumps(out, indent=1))
print("wrote docs/app_results.json")
